#!/usr/bin/env python3
"""Writes CHANGELOG.md from section 8 ("Change log") of PROJECT_RECORD.md, so history is written in one place only."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rec = (root / 'PROJECT_RECORD.md').read_text(encoding='utf-8')
m = re.search(r'^## 8\. Change log[^\n]*\n(.*?)(?=^## |\Z)', rec, re.S | re.M)
if not m: raise SystemExit('Section 8 (Change log) not found in PROJECT_RECORD.md')
body = m.group(1).strip()
(root / 'CHANGELOG.md').write_text("# Change log (newest first)\n\nGenerated from section 8 of PROJECT_RECORD.md by tools/make-changelog.py. Do not edit this file: add the entry to PROJECT_RECORD.md and run the tool (or ./tools/refresh-exports.sh).\n\n" + body + "\n", encoding='utf-8')
print('CHANGELOG.md written:', len(body.splitlines()), 'lines')
